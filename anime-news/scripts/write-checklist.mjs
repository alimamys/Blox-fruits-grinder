#!/usr/bin/env node
// Generates ASSETS.md: the exact list of artwork and audio files to supply,
// with filenames, full prompts and current status. Re-run any time:
//   npm run checklist
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const reg = JSON.parse(readFileSync(join(ROOT, 'src/data/assets.json'), 'utf8'));
const tl = JSON.parse(readFileSync(join(ROOT, 'src/generated/timeline.json'), 'utf8'));
const media = JSON.parse(readFileSync(join(ROOT, 'src/generated/media-status.json'), 'utf8'));
const has = (rel) => existsSync(join(ROOT, 'public', rel));
const box = (ok) => (ok ? '[x]' : '[ ]');
const PREVIEW_END = 20 * tl.fps;

const L = [];
L.push('# Asset checklist — THE WEEK IN ANIME: POWER UNDER PRESSURE');
L.push('');
L.push('_Generated by `npm run checklist` from `src/data/assets.json`, `src/data/script.json` and the files currently in `public/`. Do not edit by hand._');
L.push('');
L.push('Drop files into the paths below (same names). Then run `npm run timeline` (or `npm run render:preview`) and the placeholders, scratch voice and temp SFX are replaced automatically. Anything still temporary is listed in the red **ANIMATIC · TEMPORARY** flag in the top-right corner of the render.');
L.push('');
L.push('## Why these are needed');
L.push('');
L.push('No image-generation or voice-generation tool is connected to this environment (no MCP tool, no API key), and model downloads (Hugging Face, GitHub releases) are blocked by the network policy. The preview therefore uses:');
L.push('');
L.push('- **TEMPORARY placeholder art** — code-drawn blockouts in `src/components/placeholders.tsx`, labelled `PLACEHOLDER ART · Axx` on screen. Not finished anime artwork.');
L.push('- **TEMPORARY scratch narration** — offline SVOX Pico TTS (`pico2wave`, en-GB) in `public/audio/narration_scratch/`. Timing guide only; robotic.');
L.push('- **TEMPORARY procedural SFX** — synthesised in code by `scripts/make_sfx.py` into `public/audio/sfx_temp/`. Original and usable as a guide, but meant to be replaced by designed/licensed sound.');
L.push('');

// ---------------- artwork
L.push('## 1. Artwork');
L.push('');
L.push(`Format: ${reg.canvas}`);
L.push('');
L.push('**Prepend this master style prompt to every artwork prompt:**');
L.push('');
L.push('```text');
L.push(reg.masterStylePrompt);
L.push('```');
L.push('');
L.push('The **composition** line matters: the camera crops in code target those positions (stored as `anchors` in `src/data/assets.json` — adjust the numbers there if the delivered art is composed differently).');
L.push('');
L.push('Portraits of real public figures (A03, A05): many image generators refuse or restrict recognisable likenesses. Use an illustrator or a tool whose terms allow neutral editorial depictions of public figures; keep them silent and neutral, as the brief requires.');
L.push('');
L.push('| Priority | ID | File | Status |');
L.push('|---|---|---|---|');
for (const a of [...reg.assets].sort((x, y) => Number(y.inPreview) - Number(x.inPreview))) {
	const ok = !!media.assets[a.id].file;
	L.push(`| ${a.inPreview ? '**Preview**' : 'Later'} | ${a.id} | \`public/assets/${a.file}\` | ${ok ? 'supplied' : 'PLACEHOLDER'} |`);
}
L.push('');
for (const a of reg.assets) {
	const ok = !!media.assets[a.id].file;
	L.push(`### ${box(ok)} ${a.id} — \`public/assets/${a.file}\`${a.inPreview ? ' — needed for the opening preview' : ''}${a.supplementary ? ' — added (not in the brief’s 14)' : ''}`);
	L.push('');
	L.push(`Used in: ${a.scenes.join(', ')}`);
	if (a.supplementary) {
		L.push('');
		L.push('> Added because the storyboard needs a parliament interior (S01 "empty parliamentary chair", S02→S03 "chamber light" match-cut, S03 "three separate illuminated groups of desks", S07 callback) and none of the 14 brief assets covers it.');
	}
	L.push('');
	L.push('Prompt (after the master style prompt):');
	L.push('');
	L.push('```text');
	L.push(`${a.prompt} Composition: ${a.composition}`);
	L.push('```');
	if (a.layers?.length) {
		L.push('');
		L.push('Optional layers (same canvas, transparent PNG unless noted) — enable real parallax; the flattened file is still required:');
		L.push('');
		for (const l of a.layers) L.push(`- ${box(has(`assets/${l.file}`))} \`public/assets/${l.file}\` — ${l.note}`);
	}
	if (a.variants?.length) {
		L.push('');
		L.push('Optional variants (same framing) for blinks / glances:');
		L.push('');
		for (const v of a.variants) L.push(`- ${box(has(`assets/${v.file}`))} \`public/assets/${v.file}\` — ${v.note}`);
	}
	L.push('');
}

// ---------------- narration
L.push('## 2. Narration');
L.push('');
L.push('One clear English narrator, about 145–155 wpm, original/licensed recording. Record **one file per line** below (WAV preferred; MP3/M4A/FLAC also accepted), trimmed tight with no leading/trailing silence — the project inserts the pauses and times every cut and caption from the real file lengths. Speak the text exactly as written; the spoken-form numbers are already spelled out.');
L.push('');
L.push('If you prefer one continuous take per chapter, supply that instead and it can be split on the pauses into these filenames.');
L.push('');
for (const s of tl.scenes) {
	L.push(`### ${s.id} — ${s.chapter}`);
	L.push('');
	L.push('| | File | Line | Scratch length |');
	L.push('|---|---|---|---|');
	for (const c of s.cues) {
		const prev = c.startFrame < PREVIEW_END ? ' **(preview)**' : '';
		L.push(`| ${box(c.audioKind === 'final')} | \`public/audio/narration/${c.id}.wav\`${prev} | ${c.text} | ${c.seconds.toFixed(1)} s |`);
	}
	L.push('');
}

// ---------------- sfx
L.push('## 3. Sound design and music (optional replacements)');
L.push('');
L.push('Procedural placeholders exist for all of these. To replace one, put a designed/licensed file with the same name in `public/audio/sfx/` (WAV/MP3/FLAC). Beds should loop seamlessly.');
L.push('');
const SFX = {
	radio_click: 'Single radio click / brief squelch, ~0.4 s. S01 opening on black.',
	synth_pulse_bed: 'Low synth pulse bed, ~72 bpm, seamless loop. Under S01; continues quietly under S02. Ducked under speech in code.',
	bass_accent: 'Brief soft sub-bass accent, ~1 s. On S01 cuts (never under the first words).',
	water_distant: 'Distant water ambience, seamless loop. S02 Gulf.',
	tick_motif: 'Restrained ticking / light percussion motif, seamless loop. S02 Gulf, low tension, no impacts.',
};
L.push('| | File | Purpose | Current |');
L.push('|---|---|---|---|');
for (const [k, d] of Object.entries(SFX)) {
	const st = media.sfx[k];
	L.push(`| ${box(st && !st.temp)} | \`public/audio/sfx/${k}.wav\` | ${d} | ${st?.temp ? 'TEMP procedural' : 'final'} |`);
}
L.push('');
L.push('Later chapters will also need: soft room tone + paper movement and three subdued number clicks (S03); bus hum and quiet arrival ambience (S04); low crowd ambience and a distant, brief clash bed (S05); restrained electronic pulse with monitor/keyboard accents (S06); calendar-turn sound and a quiet final tone (S07). Filenames will be added here as those chapters are built.');
L.push('');
writeFileSync(join(ROOT, 'ASSETS.md'), L.join('\n'));
console.log('ASSETS.md written');
