#!/usr/bin/env node
// Writes PUBLISHING.md (title, description, chapter timestamps from the
// audio-aligned timeline, and F01–F06 source links) per brief section 7.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const tl = JSON.parse(readFileSync(join(ROOT, 'src/generated/timeline.json'), 'utf8'));
const src = JSON.parse(readFileSync(join(ROOT, 'src/data/sources.json'), 'utf8'));
const names = {S01: 'The week in anime', S02: 'Gulf diplomacy', S03: 'Israel’s coalition puzzle', S04: 'Ukraine’s local humanitarian opening', S05: 'France’s protests', S06: 'AI and Wall Street', S07: 'The vote ahead'};
const ts = (f) => {
	const s = Math.floor(f / tl.fps);
	return `${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
};
const L = [];
L.push('# Publishing text', '', '_Generated by `node scripts/write-publishing.mjs` from the audio-aligned timeline._', '');
L.push('**Title:** This Week Became an Anime | World News, 1 November 2026', '');
L.push('**Alternative title:** Power Under Pressure — The Week in Anime', '');
L.push('## Description', '', '```text');
L.push('An original animated recap of selected global news from 26 October to 1 November 2026: Gulf diplomacy, Israel’s election results, evacuations from Oleshky, protests in France, and the technology-led market sell-off. We close with the upcoming US midterm elections.');
L.push('');
L.push('The scenes are original animated illustrations of reported events. Narration is based on the reporting linked below; illustrated locations and unnamed people are not documentary footage. The episode reflects information available at the 1 November 2026 reporting cutoff.');
L.push('');
L.push('Chapters');
for (const s of tl.scenes) L.push(`${ts(s.startFrame)} ${names[s.id]}`);
L.push('');
L.push('Sources');
for (const f of src.sources) {
	L.push(`${f.id} — ${f.topic}`);
	for (const l of f.links) L.push(l);
}
L.push('```', '');
L.push(`Runtime: ${ts(tl.totalFrames)} (${tl.totalFrames} frames at ${tl.fps} fps).`, '');
L.push('If the narration is AI-generated at publication time, check the platform’s synthetic-media disclosure setting.');
writeFileSync(join(ROOT, 'PUBLISHING.md'), L.join('\n') + '\n');
console.log('PUBLISHING.md written');
