#!/usr/bin/env node
// Writes PUBLISHING.md (title, description with chapter timestamps from the
// audio-aligned timeline, readable source list, thumbnail) per brief section 7.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const tl = JSON.parse(readFileSync(join(ROOT, 'src/generated/timeline.json'), 'utf8'));
const src = JSON.parse(readFileSync(join(ROOT, 'src/data/sources.json'), 'utf8'));
const script = JSON.parse(readFileSync(join(ROOT, 'src/data/script.json'), 'utf8'));
const show = script.showName.replace(/\w\S*/g, (w) => w[0] + w.slice(1).toLowerCase());
const names = {S01: show, S02: 'Gulf diplomacy', S03: 'Israel’s coalition puzzle', S04: 'Ukraine’s local humanitarian opening', S05: 'France’s protests', S06: 'AI and Wall Street', S07: 'The vote ahead'};
const labels = {F01: 'Gulf mediation (Reuters / AP)', F02: 'Israeli election (The Times of Israel / AP)', F03: 'Oleshky evacuation (Reuters / AP)', F04: 'France protests (AFP / AP)', F05: 'US market sell-off (Reuters / AP)', F06: 'US midterms (FEC / AP)'};
const ts = (f) => {
	const s = Math.floor(f / tl.fps);
	return `${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
};
const L = [];
L.push('# Publishing text', '', '_Generated by `node scripts/write-publishing.mjs` from the audio-aligned timeline._', '');
L.push(`**Title:** ${show} | Power Under Pressure — 1 November 2026`, '');
L.push('**Alternative title:** The Week in World News, Animated | 1 November 2026', '');
L.push('**Thumbnail:** `out/thumbnail/world_news_weekly_2026-11-01_thumbnail.jpg` (1280×720; composition `Thumbnail`)', '');
L.push('## Description', '', '```text');
L.push('An animated recap of the week’s world news, 26 October – 1 November 2026: diplomacy in the Gulf, Israel’s election results, evacuations from Oleshky, protests in France, and the tech-led sell-off on Wall Street. We close with the US midterm elections on 3 November.');
L.push('');
L.push('The scenes are original animated illustrations of reported events, not documentary footage. Illustrated locations and unnamed people are not real individuals. The narration is AI-generated and based on the reporting linked below. Information is current to 1 November 2026.');
L.push('');
L.push('Chapters');
for (const s of tl.scenes) L.push(`${ts(s.startFrame)} ${names[s.id]}`);
L.push('');
L.push('Sources');
for (const f of src.sources) {
	L.push(labels[f.id] ?? f.topic);
	for (const l of f.links) L.push(l);
	L.push('');
}
L.pop();
L.push('```', '');
L.push(`Runtime: ${ts(tl.totalFrames)} (${tl.totalFrames} frames at ${tl.fps} fps).`, '');
L.push('While the narration is AI-generated, enable the platform’s altered/synthetic-content disclosure. Delete the AI-narration sentence if a human narrator is used.');
writeFileSync(join(ROOT, 'PUBLISHING.md'), L.join('\n') + '\n');
console.log('PUBLISHING.md written');
