#!/usr/bin/env python3
"""Builds dist/AutoGrindInstaller.luau: a single Studio Command Bar script that
creates all folders/remotes/templates/spawns (tools/StudioSetup.luau) AND every
Script / LocalScript / ModuleScript from src/ with its source code.

Run from the repo root:  python3 tools/build_installer.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "dist" / "AutoGrindInstaller.luau"

# src sub-folder -> (service, path inside service)
SERVICE_MAP = {
    "ReplicatedStorage": ("ReplicatedStorage", []),
    "ServerScriptService": ("ServerScriptService", []),
    "StarterPlayer/StarterPlayerScripts": ("StarterPlayer", ["StarterPlayerScripts"]),
    "StarterGui": ("StarterGui", []),
}

# Install order: modules first, then scripts.
def sort_key(path):
    name = path.name
    return (0 if not (".server." in name or ".client." in name) else 1, str(path))

def long_string(text):
    level = 0
    while "]" + "=" * level + "]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"

def describe(path):
    rel = path.relative_to(SRC)
    for prefix, (service, inner) in SERVICE_MAP.items():
        if str(rel).startswith(prefix + "/"):
            rest = rel.relative_to(prefix)
            folders = list(rest.parts[:-1])
            break
    else:
        raise SystemExit(f"Unmapped file {rel}")
    name = path.name
    if name.endswith(".server.luau"):
        cls, inst = "Script", name[: -len(".server.luau")]
    elif name.endswith(".client.luau"):
        cls, inst = "LocalScript", name[: -len(".client.luau")]
    else:
        cls, inst = "ModuleScript", name[: -len(".luau")]
    return service, inner + folders, inst, cls

entries = []
for path in sorted(SRC.rglob("*.luau"), key=sort_key):
    service, folders, inst, cls = describe(path)
    folder_list = ", ".join(f'"{f}"' for f in folders)
    entries.append(
        f'\t{{ Service = "{service}", Path = {{ {folder_list} }}, Name = "{inst}", ClassName = "{cls}",\n'
        f"\t\tSource = {long_string(path.read_text())} }},\n"
    )

setup = (ROOT / "tools" / "StudioSetup.luau").read_text()
installer = f"""--[[
	AutoGrindInstaller  (GENERATED by tools/build_installer.py - do not edit by hand)

	HOW TO USE
	  1. Open your place in Roblox Studio.
	  2. View > Command Bar.
	  3. Paste this ENTIRE file into the Command Bar and press Enter.
	  4. Check the Output window for "[Installer] Done".
	  5. Press Play.

	Re-running updates the script sources and keeps everything else.
]]

do
{setup}
end

local SCRIPTS = {{
{''.join(entries)}}}

for _, entry in SCRIPTS do
	local parent: Instance = game:GetService(entry.Service)
	for _, folderName in entry.Path do
		local child = parent:FindFirstChild(folderName)
		if not child then
			child = Instance.new("Folder")
			child.Name = folderName
			child.Parent = parent
		end
		parent = child
	end

	local existing = parent:FindFirstChild(entry.Name)
	if existing and existing.ClassName ~= entry.ClassName then
		warn(("[Installer] Replacing %s (%s -> %s)"):format(existing:GetFullName(), existing.ClassName, entry.ClassName))
		existing:Destroy()
		existing = nil
	end
	local scriptInstance = existing or Instance.new(entry.ClassName)
	scriptInstance.Name = entry.Name;
	(scriptInstance :: any).Source = entry.Source
	scriptInstance.Parent = parent
	print(("[Installer] %s %s (%s)"):format(if existing then "Updated" else "Created", scriptInstance:GetFullName(), entry.ClassName))
end

print("[Installer] Done. Press Play and click 'Auto Grind' (or press G).")
"""
OUT.parent.mkdir(exist_ok=True)
OUT.write_text(installer)
print(f"Wrote {OUT.relative_to(ROOT)} ({len(entries)} scripts)")
