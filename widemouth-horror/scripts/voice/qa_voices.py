#!/usr/bin/env python3
"""Automatic QA for generated voice lines: transcribe every take with Whisper and
flag lines whose words don't match the script (skipped / garbled / hallucinated
words) or whose length is implausible. Run in the Chatterbox venv (it has torch +
transformers):

    .venv-chatterbox/bin/python scripts/voice/qa_voices.py                 # all lines
    .venv-chatterbox/bin/python scripts/voice/qa_voices.py --provider chatterbox
    .venv-chatterbox/bin/python scripts/voice/qa_voices.py --retake-failed  # re-roll flagged lines (best of 4)

Writes build/voice_qa.json. Effects-heavy lines (radio, PA, whisper) get a lower
threshold because the processing itself makes recognition harder.
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import numpy as np  # noqa: E402

import dsp  # noqa: E402

ROOT = HERE.parent.parent
DATA = ROOT / 'build' / 'voice-data.json'
CACHE = ROOT / 'public' / 'audio' / '.voice-cache.json'
OUT = ROOT / 'build' / 'voice_qa.json'

ONES = 'zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen'.split()
TENS = 'zero ten twenty thirty forty fifty sixty seventy eighty ninety'.split()


def num_words(n: int) -> str:
    if n < 20:
        return ONES[n]
    if n < 100:
        return TENS[n // 10] + ('' if n % 10 == 0 else ' ' + ONES[n % 10])
    if n < 1000:
        rest = n % 100
        return ONES[n // 100] + ' hundred' + ('' if rest == 0 else ' ' + num_words(rest))
    if n < 10000 and n % 100:
        return num_words(n // 100) + ' ' + num_words(n % 100)  # 1226 -> twelve twenty six (times, years)
    return str(n)


# spellings Whisper (or the script) may use for the same spoken word
CANON = {
    'than': 'then', 'mom': 'mum', 'moms': 'mums', 'clark': 'clarke', "who's": 'whose',
    'mam': "ma'am", 'madam': "ma'am", 'ok': 'okay', 'grey': 'gray', 'alright': 'all right',
    'hannah': 'hana', 'hanna': 'hana', 'meter': 'metre',
    'neighbours': 'neighbors', 'neighbour': 'neighbor', 'wifi': 'wi fi', 'storey': 'story', 'goatman': 'goat man', 'firepit': 'fire pit',
    'treeline': 'tree line', 'nosebleed': 'nose bleed', 'fivethirty': 'five thirty', 'okay': 'ok',
}


def norm(text: str) -> list[str]:
    t = text.lower()
    t = re.sub(r'\[[^\]]*\]', ' ', t)  # audio tags
    t = re.sub(r'\b((?:[a-z]\.){2,})', lambda m: m.group(1).replace('.', '') + ' ', t)  # G.P.S. / a.m.
    t = re.sub(r'(\d+):(\d+)', lambda m: f'{m.group(1)} {m.group(2)}', t)
    t = re.sub(r'\d+', lambda m: ' ' + num_words(int(m.group(0))) + ' ', t)
    t = t.replace('-', ' ').replace('\u2019', "'")
    t = re.sub(r"[^a-z' ]+", ' ', t)
    words = [CANON.get(w.strip("'"), w.strip("'")) for w in t.split()]
    words = ' '.join(words).split()
    return [w for w in words if w and w not in ('mm', 'hm', 'mmhm', 'uh', 'um', 'ha')]


def similarity(a: list[str], b: list[str]) -> float:
    if not a and not b:
        return 1.0
    return difflib.SequenceMatcher(None, a, b).ratio()


HEAVY = ('marineRadio', 'pa', 'paSoft', 'multiSpeaker', 'whisper', 'whisperClose', 'distant', 'crowdRoom', 'phone', 'closet', 'shout', 'door', 'doorGap', 'creature', 'thing')


def load_asr(model: str = 'openai/whisper-base.en'):
    from asr import load

    return load(model)


def assess(asr, line: dict, x: np.ndarray, sr: int, threshold: float = 0.72) -> dict:
    """Transcribe one take and compare it to the script. score is similarity minus a
    penalty for an implausible length, so it can rank several takes of one line."""
    if x.ndim == 2:
        x = x.mean(axis=1)
    x16 = dsp.resample(x, sr, 16000).astype(np.float32)
    heard = asr({'raw': x16, 'sampling_rate': 16000})['text'].strip()
    want = norm(line.get('spokenText') or line['text'])
    sim = similarity(want, norm(heard))
    words = max(1, len(want))
    dur = len(x) / sr
    expected = words / 2.6 + 0.4
    heavy = line['audioEffect'] in HEAVY
    thr = threshold - (0.2 if heavy else 0.0) - (0.15 if words <= 2 else 0.0)
    bad_len = dur > expected * 2.6 + 1.0 or dur < expected * 0.35
    return {'similarity': round(sim, 2), 'duration': round(dur, 2), 'heard': heard,
            'ok': sim >= thr and not bad_len, 'score': sim - (0.5 if bad_len else 0.0)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--provider', help='only check lines generated by this provider')
    ap.add_argument('--model', default='openai/whisper-base.en')
    ap.add_argument('--threshold', type=float, default=0.72)
    ap.add_argument('--retake-failed', action='store_true')
    ap.add_argument('--best-of', type=int, default=4, help='takes to try per flagged line when re-rolling')
    args = ap.parse_args()

    data = json.loads(DATA.read_text())
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    asr = load_asr(args.model)
    flagged, results = [], []
    for line in data['VOICE_LINES']:
        f = ROOT / 'public' / 'audio' / line['filename']
        prov = cache.get(line['filename'], {}).get('provider')
        if not f.exists() or (args.provider and prov != args.provider) or line.get('noSubtitle'):
            continue  # wordless screams are not checked for words
        x, sr = dsp.read_wav(str(f))
        r = assess(asr, line, x, sr, args.threshold)
        results.append({'id': line['id'], 'provider': prov, **{k: v for k, v in r.items() if k != 'score'}})
        if not r['ok']:
            flagged.append(line['id'])
            print(f'  FLAG {line["id"]:32s} sim {r["similarity"]:.2f} dur {r["duration"]:5.2f}s  heard: {r["heard"][:80]}')
    OUT.write_text(json.dumps(results, indent=1))
    print(f'\nChecked {len(results)} lines, flagged {len(flagged)} -> {OUT.relative_to(ROOT)}')
    if args.retake_failed and flagged:
        prov = args.provider or 'chatterbox'
        cmd = [sys.executable, str(HERE / 'generate_voices.py'), '--provider', prov, '--retake', ','.join(flagged), '--best-of', str(args.best_of)]
        print('$', ' '.join(cmd))
        return subprocess.call(cmd)
    return 0


if __name__ == '__main__':
    sys.exit(main())
