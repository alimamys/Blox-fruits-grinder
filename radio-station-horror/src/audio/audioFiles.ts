// Safe lookup of optional audio files in public/.
//
// Remotion fails a render if an <Audio> points at a missing file, so every
// audio element first checks that the file actually exists. The list of
// files comes from getStaticFiles(), which Remotion fills in both in the
// Studio (live – drop a file in and it is picked up) and when rendering.
import {getStaticFiles, staticFile} from 'remotion';
import type {SfxName} from '../data/types';

/** The required hook names. Put real recordings at public/audio/<name>.wav (or .mp3). */
export const SFX_NAMES: SfxName[] = [
	'low_ambient_hum',
	'radio_static',
	'three_beeps',
	'knocking',
	'breathing',
	'electrical_buzz',
	'impact',
	'glass_break',
	'motel_ambience',
	'scratching',
	'creak',
	'whisper',
	'phone_buzz',
	'tv_on',
	'train',
];

/** Continuous narration track. Starts at the beginning of NARRATOR_START_CHAPTER. */
export const NARRATOR_FILE = 'audio/narrator';
export const NARRATOR_START_CHAPTER = 'coldOpen';

const EXTENSIONS = ['.wav', '.mp3', '.ogg', '.m4a'];

let cached: Set<string> | null = null;
let cachedAt = -1;

const available = (): Set<string> => {
	// Re-read at most every 2 s (Studio updates the list when files change).
	const now = Date.now();
	if (cached && now - cachedAt < 2000) {
		return cached;
	}
	let names: string[] = [];
	try {
		names = getStaticFiles().map((f) => f.name.replace(/^\/+/, ''));
	} catch {
		names = [];
	}
	cached = new Set(names);
	cachedAt = now;
	return cached;
};

/**
 * Returns a staticFile() URL for `base` + the first existing extension, or null.
 * @param base path inside public/ without extension, e.g. "audio/narrator"
 */
export const findAudio = (base: string): string | null => {
	const files = available();
	for (const ext of EXTENSIONS) {
		const name = `${base}${ext}`;
		if (files.has(name)) {
			return staticFile(name);
		}
	}
	return null;
};

/** Real recording first, then the procedural placeholder generated by scripts/prepare-assets.mjs. */
export const findSfx = (name: SfxName): string | null =>
	findAudio(`audio/${name}`) ?? findAudio(`audio/placeholders/${name}`);
